def lit(v):
    r = repr(float(v))
    if r == "nan": return "@double.not_a_number"
    if "e" in r:
        m, e = r.split("e"); m += "" if "." in m else ".0"; return m + "e" + e
    return r if "." in r else r + ".0"
print("// Generated by tools/gen_polygon.py with geographiclib (Python) 2.1. Do not edit.\n")
print("///|\nlet polygon_cases : Array[(String, Array[(Double, Double)], Double, Double, Double)] = [")
for name, pts in polys.items():
    p = g.Polygon()
    for la, lo in pts: p.AddPoint(la, lo)
    n, per, area = p.Compute(False, True)
    _, _, area_r = p.Compute(True, False)
    print(f'  ("{name}", [{", ".join(f"({lit(a)}, {lit(b)})" for a, b in pts)}], {lit(per)}, {lit(area)}, {lit(area_r)}),')
print("]\n")
