"""World Magnetic Model 2025 coefficients and official test values.

Writes
  src/magnetic/wmm2025_data.mbt              Gauss coefficients (WMM.COF)
  src/magnetic/wmm2025_testvalues_data_test.mbt  NOAA/BGS test values

Sources (NOAA NCEI, https://www.ncei.noaa.gov/products/world-magnetic-model):
  WMM2025COF.zip  https://www.ncei.noaa.gov/sites/default/files/2024-12/WMM2025COF.zip
      WMM2025COF/WMM.COF                  the coefficients
      WMM2025COF/WMM2025_TestValues.txt   100 points, 6 decimals (double precision)
  WMM2025_TEST_VALUES.txt
      https://www.ncei.noaa.gov/sites/default/files/2025-02/WMM2025_TEST_VALUES.txt
      12 points from Table 6 of the technical report, 0.1 nT / 0.01 deg, with
      grid variation

The WMM is a joint product of the US National Geospatial-Intelligence Agency
and the UK Defence Geographic Centre, produced by NOAA NCEI and the British
Geological Survey. NCEI states that it is in the public domain and not under
copyright (17 U.S.C. 403 notice: the coefficients and test values are U.S.
Government material, not subject to copyright protection).

Model citation: NOAA NCEI Geomagnetic Modeling Team; British Geological
Survey. 2024: World Magnetic Model 2025. https://doi.org/10.25921/aqfd-sd83
Report: Chulliat et al. 2025, The US/UK World Magnetic Model for 2025-2030:
Technical Report. https://doi.org/10.25923/prbc-s316

Usage:
  python3 tools/gen_wmm.py WMM.COF WMM2025_TestValues.txt WMM2025_TEST_VALUES.txt
"""
import hashlib
import sys

SHA256 = {
    "cof": "dfa8597825af4e0b87ff4198a5b4fb661b3c49f4cd090cd0164e0259b075582f",
    "precise": "e6975b093dddeb6153e0b23cc418425c438167e7c5b1dd795da379cb654f5819",
    "table6": "ae289c94e2200e4deeae2dfdedf543a8a0e93096512b30d6a754199731f570d0",
}
NMAX = 12
DATA_OUT = "src/magnetic/wmm2025_data.mbt"
TEST_OUT = "src/magnetic/wmm2025_testvalues_data_test.mbt"


def read_checked(path, key):
    raw = open(path, "rb").read()
    got = hashlib.sha256(raw).hexdigest()
    if got != SHA256[key]:
        sys.exit(f"{path}: sha256 {got} does not match {SHA256[key]}")
    return raw.decode("ascii")


def lit(v):
    if v != v:
        return "@double.not_a_number"
    r = repr(float(v))
    if "e" in r:
        m, e = r.split("e")
        if "." not in m:
            m += ".0"
        r = m + "e" + e
    return r


def array(name, doc, values, per_line=6):
    out = ["///|", f"/// {doc}", f"let {name} : FixedArray[Double] = ["]
    for i in range(0, len(values), per_line):
        out.append("  " + ", ".join(lit(v) for v in values[i:i + per_line]) + ",")
    out.append("]")
    return "\n".join(out)


def coefficients(text):
    lines = text.splitlines()
    head = lines[0].split()
    epoch, name = float(head[0]), head[1]
    size = (NMAX + 1) * (NMAX + 2) // 2
    g, h, gd, hd = ([0.0] * size for _ in range(4))
    seen = set()
    for line in lines[1:]:
        f = line.split()
        if not f or f[0].startswith("9999"):
            break
        n, m = int(f[0]), int(f[1])
        k = n * (n + 1) // 2 + m
        g[k], h[k], gd[k], hd[k] = map(float, f[2:6])
        seen.add((n, m))
    want = {(n, m) for n in range(1, NMAX + 1) for m in range(n + 1)}
    if seen != want:
        sys.exit("coefficient file is not complete to degree 12")
    return epoch, name, g, h, gd, hd


def rows(text, ncols):
    out = []
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        f = [float(x) for x in line.split()]
        if len(f) != ncols:
            sys.exit(f"expected {ncols} columns: {line!r}")
        out.append(f)
    return out


def table(name, doc, data):
    out = ["///|", f"/// {doc}", f"let {name} : Array[FixedArray[Double]] = ["]
    for r in data:
        out.append("  [" + ", ".join(lit(v) for v in r) + "],")
    out.append("]")
    return "\n".join(out)


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    epoch, name, g, h, gd, hd = coefficients(read_checked(sys.argv[1], "cof"))
    precise = rows(read_checked(sys.argv[2], "precise"), 18)
    table6 = rows(read_checked(sys.argv[3], "table6"), 19)
    if len(precise) != 100 or len(table6) != 12:
        sys.exit("unexpected number of test values")

    data = [
        "// Generated by tools/gen_wmm.py. Do not edit.",
        f"// {name} Gauss coefficients from NOAA NCEI WMM.COF (epoch {epoch}),",
        "// https://www.ncei.noaa.gov/products/world-magnetic-model",
        "// U.S. Government material, not subject to copyright protection",
        "// (17 U.S.C. 403). NOAA NCEI Geomagnetic Modeling Team; British",
        "// Geological Survey. 2024: World Magnetic Model 2025.",
        "// https://doi.org/10.25921/aqfd-sd83",
        "// Index k = n * (n + 1) / 2 + m for degree n and order m, n <= 12.",
        "",
        "///|",
        f"let wmm2025_epoch : Double = {lit(epoch)}",
        "",
        array("wmm2025_g", "Main field g(n, m) at the epoch (nT).", g),
        "",
        array("wmm2025_h", "Main field h(n, m) at the epoch (nT).", h),
        "",
        array("wmm2025_gdot", "Secular variation of g(n, m) (nT/yr).", gd),
        "",
        array("wmm2025_hdot", "Secular variation of h(n, m) (nT/yr).", hd),
        "",
    ]
    with open(DATA_OUT, "w") as fh:
        fh.write("\n".join(data))

    test = [
        "// Generated by tools/gen_wmm.py. Do not edit.",
        "// Official WMM2025 test values from NOAA NCEI (U.S. Government",
        "// material, not subject to copyright protection, 17 U.S.C. 403).",
        "",
        table(
            "wmm2025_precise",
            "WMM2025COF/WMM2025_TestValues.txt (double precision, 6 decimals). "
            "Columns: year, height (km), lat, lon, D, I (deg), H, X, Y, Z, F (nT), "
            "dD/dt, dI/dt (deg/yr), dH/dt, dX/dt, dY/dt, dZ/dt, dF/dt (nT/yr).",
            precise,
        ),
        "",
        table(
            "wmm2025_table6",
            "WMM2025_TEST_VALUES.txt (report Table 6, rounded). "
            "Columns: year, height (km), lat, lon, X, Y, Z, H, F (nT), I, D, GV (deg), "
            "Xdot, Ydot, Zdot, Hdot, Fdot (nT/yr), Idot, Ddot (deg/yr).",
            table6,
        ),
        "",
    ]
    with open(TEST_OUT, "w") as fh:
        fh.write("\n".join(test))
    print(f"wrote {DATA_OUT} and {TEST_OUT}")


if __name__ == "__main__":
    main()
