"""Reference values for transverse Mercator / UTM / UPS from PROJ via pyproj.

PROJ's tmerc uses the Poder/Engsager extended transverse Mercator (also a
6th-order Krüger series), so agreement should be at the nanometre level
near the central meridian.  Usage: python3 tools/gen_utm.py
"""
import random, pyproj
random.seed(20261009)
def lit(v):
    r = repr(float(v))
    if "e" in r:
        m, e = r.split("e"); m += "" if "." in m else ".0"; return m + "e" + e
    return r if "." in r else r + ".0"
out = ["// Generated by tools/gen_utm.py with pyproj %s / PROJ %s. Do not edit." % (pyproj.__version__, pyproj.proj_version_str), ""]
# Transverse Mercator, k0 = 0.9996, random central meridians
rows = []
for i in range(300):
    lon0 = random.choice([-177, -93, -3, 3, 75, 105, 111, 117, 123, 177])
    lat = random.uniform(-80, 84)
    dlon = random.uniform(-9, 9) if i % 3 else random.uniform(-3, 3)
    lon = lon0 + dlon
    p = pyproj.Proj(f"+proj=tmerc +lat_0=0 +lon_0={lon0} +k=0.9996 +x_0=0 +y_0=0 +ellps=WGS84")
    x, y = p(lon, lat); f = p.get_factors(lon, lat)
    rows.append((lat, lon, lon0, x, y, f.meridian_convergence, f.meridional_scale))
out += ["///|", "/// (lat, lon, lon0, x, y, gamma, k)",
        "let tm_cases : Array[(Double, Double, Double, Double, Double, Double, Double)] = ["]
out += ["  (" + ", ".join(map(lit, r)) + ")," for r in rows]
out += ["]", ""]
# UTM via EPSG codes, standard zones (no Norway/Svalbard exceptions in these samples)
urows = []
for i in range(200):
    lat = random.uniform(-79.9, 55.9)
    lon = random.uniform(-180, 179.999)
    zone = int((lon + 180) // 6) + 1
    epsg = (32600 if lat >= 0 else 32700) + zone
    t = pyproj.Transformer.from_crs(4326, epsg, always_xy=True)
    e, n = t.transform(lon, lat)
    urows.append((lat, lon, zone, 1.0 if lat >= 0 else 0.0, e, n))
out += ["///|", "/// (lat, lon, zone, north(1/0), easting, northing)",
        "let utm_cases : Array[(Double, Double, Int, Double, Double, Double)] = ["]
out += ["  (%s, %s, %d, %s, %s, %s)," % (lit(r[0]), lit(r[1]), r[2], lit(r[3]), lit(r[4]), lit(r[5])) for r in urows]
out += ["]", ""]
# UPS north (EPSG:32661) and south (EPSG:32761)
prow = []
for i in range(100):
    north = i % 2 == 0
    lat = random.uniform(84, 90) if north else random.uniform(-90, -80)
    lon = random.uniform(-180, 180)
    t = pyproj.Transformer.from_crs(4326, 32661 if north else 32761, always_xy=True)
    e, n = t.transform(lon, lat)
    prow.append((lat, lon, 1.0 if north else 0.0, e, n))
out += ["///|", "/// (lat, lon, north(1/0), easting, northing)",
        "let ups_cases : Array[(Double, Double, Double, Double, Double)] = ["]
out += ["  (" + ", ".join(map(lit, r)) + ")," for r in prow]
out += ["]"]
open("src/utm/proj_data_test.mbt", "w").write("\n".join(out) + "\n")
print(len(rows), len(urows), len(prow))
