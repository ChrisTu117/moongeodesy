"""Write the README code blocks into compiled tests.

README.md has two ```moonbit blocks: the Usage tour and the one in
中文简介. This script copies each into a test in src/examples/readme_check,
so `moon test` compiles and runs exactly the code a reader sees. CI runs it
and fails if the generated files differ from the committed ones.

Usage: python3 tools/sync_readme_tests.py
"""
import re

README = "README.md"
OUTS = [
    ("src/examples/readme_check/readme_test.mbt", "readme"),
    ("src/examples/readme_check/readme2_test.mbt", "readme zh"),
]


def main():
    text = open(README, encoding="utf-8").read()
    blocks = re.findall(r"```moonbit\n(.*?)```", text, re.S)
    if len(blocks) != len(OUTS):
        raise SystemExit(f"expected {len(OUTS)} moonbit blocks, found {len(blocks)}")
    for (path, name), code in zip(OUTS, blocks):
        names = re.findall(r"^let (\w+)", code, re.M)
        body = "".join("  " + line + "\n" if line.strip() else "\n" for line in code.splitlines())
        out = (
            "// Generated by tools/sync_readme_tests.py from README.md. Do not edit.\n"
            "\n"
            "///|\n"
            f'test "{name}" {{\n'
            + body
            + f"  ignore(({', '.join(names)}))\n"
            "}\n"
        )
        open(path, "w", encoding="utf-8").write(out)
        print(f"wrote {path}: {len(names)} bindings")


if __name__ == "__main__":
    main()
