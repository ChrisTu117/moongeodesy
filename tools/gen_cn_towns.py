"""Generate src/cn/towns_data_test.mbt: GeoNames towns inside the GCJ-02 box.

The test checks `out_of_china` against GeoNames (https://www.geonames.org/,
CC BY 4.0), a data set independent of the Natural Earth borders used to build
the foreign region: every town of 5000 or more people inside the box.

- Towns whose GeoNames country is not CN, HK, MO, or TW must be foreign
  (not offset). Towns on islets missing from Natural Earth are listed as
  exceptions, by name, so the README can quote them.
- Towns in CN, HK, MO, or TW must not be foreign.
- Left out: towns within 0.03 degree (about 3 km) of China's land border,
  where the simplified border is ambiguous, and towns that GeoNames assigns
  to another country but Natural Earth's China point of view assigns to
  China (disputed areas); both counts are written to the file header.

GeoNames publishes a new dump every day, so the file records the dump's
SHA-256 instead of checking one.

Needs: pip install shapely
Usage:
    python3 tools/gen_cn_towns.py cities5000.txt countries.geojson minor_islands.geojson
(cities5000.txt is inside https://download.geonames.org/export/dump/cities5000.zip)
"""
import hashlib
import json
import os
import sys

from shapely import prepared
from shapely.geometry import Point

sys.path.insert(0, os.path.dirname(__file__))
import gen_china_boundary as gb  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "cn", "towns_data_test.mbt")
CHINESE = {"CN", "HK", "MO", "TW"}
NEAR_BORDER = 0.03


def flat(rows):
    out, line = [], "  "
    for lat, lon in rows:
        item = f"{lat!r}, {lon!r}, "
        if len(line) + len(item) > 80:
            out.append(line.rstrip())
            line = "  "
        line += item
    out.append(line.rstrip())
    return "\n".join(out)


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    raw = open(sys.argv[1], "rb").read()
    digest = hashlib.sha256(raw).hexdigest()
    countries = gb.load("countries", sys.argv[2])
    minor = gb.load("minor", sys.argv[3])
    region, china, _ = gb.build(countries, minor)
    region = prepared.prep(region.simplify(gb.TOL, preserve_topology=True))
    foreign_land = [
        f for f in countries["features"] if f["properties"]["ADM0_A3"] not in gb.INSIDE
    ]
    from shapely.geometry import shape
    from shapely.ops import unary_union
    foreign = unary_union([shape(f["geometry"]) for f in foreign_land])
    border = china.boundary.intersection(foreign.buffer(0.002)).buffer(NEAR_BORDER)
    border = prepared.prep(border)
    pchina = prepared.prep(china)

    foreign_towns, china_towns, exceptions = [], [], []
    disputed = near = 0
    for line in raw.decode("utf-8").splitlines():
        f = line.split("\t")
        name, lat, lon, cc = f[1], float(f[4]), float(f[5]), f[8]
        if not (gb.W <= lon <= gb.E and gb.S <= lat <= gb.N):
            continue
        p = Point(lon, lat)
        if border.contains(p):
            near += 1
            continue
        if cc in CHINESE:
            china_towns.append((lat, lon))
            continue
        if pchina.contains(p):
            disputed += 1
            continue
        if region.contains(p):
            foreign_towns.append((lat, lon))
        else:
            exceptions.append((name, cc, lat, lon))
    out = [
        "// Generated by tools/gen_cn_towns.py. Do not edit.",
        "// GeoNames cities5000 (https://www.geonames.org/, CC BY 4.0),",
        f"// dump SHA-256 {digest}.",
        f"// Towns in the GCJ-02 box: {len(foreign_towns) + len(exceptions)} foreign,",
        f"// {len(china_towns)} in CN/HK/MO/TW; left out: {near} within {NEAR_BORDER} deg of",
        f"// China's land border, {disputed} disputed (China in Natural Earth's China view).",
        "",
        "///|",
        "/// Foreign towns (lat, lon pairs): must not get the GCJ-02 offset.",
        "let foreign_towns : FixedArray[Double] = [",
        flat(foreign_towns),
        "]",
        "",
        "///|",
        "/// Towns in China, Hong Kong, Macau, and Taiwan: must get the offset.",
        "let china_towns : FixedArray[Double] = [",
        flat(china_towns),
        "]",
        "",
        "///|",
        "/// Foreign towns on islets missing from Natural Earth 1:10m; they are",
        "/// treated as sea and offset. Name, country, lat, lon.",
        "let foreign_town_exceptions : Array[(String, String, Double, Double)] = [",
    ]
    for name, cc, lat, lon in exceptions:
        out.append(f"  ({json.dumps(name, ensure_ascii=False)}, {json.dumps(cc)}, {lat!r}, {lon!r}),")
    out += ["]", ""]
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print(f"wrote {OUT}: {len(foreign_towns)} foreign, {len(china_towns)} Chinese, "
          f"{len(exceptions)} exceptions {exceptions}, {near} near border, {disputed} disputed")


if __name__ == "__main__":
    main()
