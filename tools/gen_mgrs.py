"""MGRS reference strings from the `mgrs` Python package (NGA GeoTrans).
Usage: python3 tools/gen_mgrs.py"""
import random, warnings, mgrs
warnings.simplefilter("ignore")
random.seed(7)
m = mgrs.MGRS()
pts = [(39.9087, 116.3975), (22.5431, 114.0579), (31.2304, 121.4737), (60.39, 5.32),
       (78.22, 15.65), (-33.8688, 151.2093), (0.0, 0.0), (-0.0001, 0.0001), (83.9, -45),
       (-79.9, 170), (84.5, 10), (89.9, -100), (-85, -120), (-89.9, 45), (51.4778, -0.0015)]
pts += [(random.uniform(-80, 84), random.uniform(-180, 180)) for _ in range(250)]
pts += [(random.uniform(84, 89.99), random.uniform(-180, 180)) for _ in range(25)]
pts += [(random.uniform(-89.99, -80), random.uniform(-180, 180)) for _ in range(25)]
def lit(v):
    r = repr(float(v))
    if "e" in r:
        a, e = r.split("e"); a += "" if "." in a else ".0"; return a + "e" + e
    return r if "." in r else r + ".0"
out = ["// Generated by tools/gen_mgrs.py with mgrs (GeoTrans) %s. Do not edit." % getattr(mgrs, "__version__", "?"), "",
       "///|", "/// (lat, lon, precision, mgrs)", "let mgrs_cases : Array[(Double, Double, Int, String)] = ["]
for i, (la, lo) in enumerate(pts):
    p = 5 if i % 4 else (i // 4) % 6
    s = m.toMGRS(la, lo, MGRSPrecision=p)
    s = s.decode() if isinstance(s, bytes) else s
    out.append('  (%s, %s, %d, "%s"),' % (lit(la), lit(lo), p, s))
out.append("]")
open("src/utm/mgrs_data_test.mbt", "w").write("\n".join(out) + "\n")
print(len(pts))
