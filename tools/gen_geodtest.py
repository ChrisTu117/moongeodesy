"""Generate src/geodesic/geodtest_test.mbt from GeographicLib's GeodTest-short.dat.

GeodTest-short.dat (10,000 high-precision WGS-84 test geodesics by C. Karney,
https://doi.org/10.5281/zenodo.32156) is downloaded from
https://sourceforge.net/projects/geographiclib/files/testdata/
Every STEP-th line is embedded as MoonBit literals (values kept as strings
in the exact decimal form given in the data set).

Usage: python3 tools/gen_geodtest.py /path/to/GeodTest-short.dat [STEP]
"""
import sys
path = sys.argv[1]
step = int(sys.argv[2]) if len(sys.argv) > 2 else 10
lines = open(path).read().split("\n")
rows = [l.split() for i, l in enumerate(lines) if l.strip() and i % step == 0]
def lit(x):
    v = float(x)
    r = repr(v)
    if "e" in r:
        m, e = r.split("e")
        if "." not in m: m += ".0"
        r = m + "e" + e
    elif "." not in r and "inf" not in r and "nan" not in r:
        r += ".0"
    return r
out = ["// Generated by tools/gen_geodtest.py from GeodTest-short.dat (every %d-th line)." % step,
       "// Columns: lat1 lon1 azi1 lat2 lon2 azi2 s12 a12 m12 S12. Do not edit.", "",
       "///|", "let geodtest : Array[FixedArray[Double]] = ["]
for r in rows:
    out.append("  [" + ", ".join(lit(x) for x in r) + "],")
out.append("]")
open("src/geodesic/geodtest_data_test.mbt", "w").write("\n".join(out) + "\n")
print(len(rows), "rows")
