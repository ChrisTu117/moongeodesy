"""GeodesicExact reference values from GeographicLib's GeodSolve -E.

GeodSolve is the command-line front end of GeographicLib::GeodesicExact
(Charles Karney, GeographicLib, MIT/X11 License). It ships in a
GeographicLib build; this file was checked against version 2.5
(https://github.com/geographiclib/geographiclib/tree/r2.5). Pass -E so
the elliptic-integral geodesic is used. The vectors are numeric results
of that tool. They are not a copy of the GeodesicExact source.

Columns written into the MoonBit table:
  a, f, kind (0 inverse, 1 direct), four inputs,
  then lat1 lon1 azi1 lat2 lon2 azi2 s12 a12 m12 M12 M21 S12.

Usage:
  python3 tools/gen_geodesic_exact.py [path/to/GeodSolve]
"""
import subprocess
import sys

TOOL = sys.argv[1] if len(sys.argv) > 1 else "GeodSolve"
OUT = "src/geodesic/geodesic_exact_data_test.mbt"

# Inverse endpoints. Several are meridian, equator, pole, short, or nearly antipodal.
INVERSE = [
    (40.6, -73.8, 1.5, 0.0),
    (0.0, 0.0, 0.0, 90.0),
    (0.0, 0.0, 0.0, 179.0),
    (90.0, 0.0, 0.0, 0.0),
    (-90.0, 10.0, 90.0, 20.0),
    (10.0, 20.0, -30.0, 140.0),
    (1.0, 2.0, 1.000001, 2.000001),
    (0.0, 0.0, 0.5, 179.5),
    (48.522876735459, 0.0, -48.52287673545898293, 179.599720456223079643),
    (20.001, 0.0, 20.001, 0.0),
    (89.9, 0.0, 89.9, 0.1),
    (-20.0, 179.0, 15.0, -179.0),
    (30.0, 10.0, 30.0, 10.0),
    (5.0, -170.0, -40.0, 20.0),
    (60.0, 30.0, -10.0, 100.0),
]

# (a, f). |f| is above the series limit 1/50, plus one WGS-84 check.
ELLIPSOIDS = [
    (6378137.0, 0.1),
    (6378137.0, 0.2),
    (6378137.0, 0.05),
    (6400000.0, -0.1),
    (6400000.0, -0.2),
    (6378137.0, 0.5),
    (6378137.0, 1.0 / 298.257223563),
]

# Direct: lat1 lon1 azi1 s12.
DIRECT = [
    (6378137.0, 0.1, 40.6, -73.8, 45.0, 10000000.0),
    (6378137.0, 0.2, -33.0, 151.0, 270.0, 5000000.0),
    (6400000.0, -0.1, 10.0, 20.0, 123.0, 8000000.0),
    (6378137.0, 0.5, 0.0, 0.0, 90.0, 2000000.0),
    (6378137.0, 0.1, 80.0, 0.0, 0.0, 3000000.0),
    (6378137.0, 0.05, 0.0, 179.0, 90.0, 1000.0),
]


def solve(a, f, inverse, values):
    cmd = [TOOL, "-E", "-f", "-p", "16", "-e", repr(a), repr(f)]
    if inverse:
        cmd.append("-i")
    line = " ".join(repr(x) for x in values) + "\n"
    out = subprocess.check_output(cmd, input=line, text=True)
    nums = [float(x) for x in out.split()]
    if len(nums) != 12:
        raise SystemExit(f"expected 12 fields, got {len(nums)}: {out}")
    return nums


def lit(x):
    return f"{x:.16e}"


def main():
    rows = []
    for a, f in ELLIPSOIDS:
        for p in INVERSE:
            rows.append([a, f, 0.0, *p, *solve(a, f, True, p)])
    for a, f, lat1, lon1, azi, s12 in DIRECT:
        rows.append([a, f, 1.0, lat1, lon1, azi, s12, *solve(a, f, False, (lat1, lon1, azi, s12))])
    lines = [
        "// Generated by tools/gen_geodesic_exact.py from GeodSolve -E (GeographicLib 2.5).",
        "// Columns: a, f, kind (0 inverse, 1 direct), four inputs, then",
        "// lat1 lon1 azi1 lat2 lon2 azi2 s12 a12 m12 M12 M21 S12. Do not edit.",
        "",
        "///|",
        "let exact_cases : Array[FixedArray[Double]] = [",
    ]
    for row in rows:
        lines.append("  [" + ", ".join(lit(x) for x in row) + "],")
    lines.append("]")
    lines.append("")
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {len(rows)} rows to {OUT}")


if __name__ == "__main__":
    main()
