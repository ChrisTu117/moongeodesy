import random
import coord_convert.transform as t
random.seed(20261009)
pts=[(39.9087,116.3975),(31.2304,121.4737),(22.5431,114.0579),(23.1291,113.2644),(30.5728,104.0668),(43.8256,87.6168),(18.2528,109.5119),(45.8038,126.5349),(29.6500,91.1000),(25.0330,121.5654)]
pts+= [(random.uniform(18,53),random.uniform(74,134)) for _ in range(190)]
def f(x): return repr(float(x))
out=["// Generated by tools/gen_cn.py from coord-convert 0.2.1 (Python, Krasovsky a=6378245). Do not edit.","","///|","let cn_vectors : Array[(Double, Double, Double, Double, Double, Double)] = ["]
for la,lo in pts:
    gl,ga=t.wgs2gcj(lo,la); bl,ba=t.gcj2bd(gl,ga); g=(ga,gl); b=(ba,bl)
    out.append(f"  ({f(la)}, {f(lo)}, {f(g[0])}, {f(g[1])}, {f(b[0])}, {f(b[1])}),")
out.append("]")
open('./src/cn/vectors_test.mbt','w').write("\n".join(out)+"\n")
