"""Cross-check vectors from the reference Python implementation (geographiclib 2.1).

Writes src/geodesic/pyref_data_test.mbt containing, for every STEP-th line of
GeodTest-short.dat plus a set of hand-picked edge cases, the outputs of
Geodesic.WGS84.Inverse/Direct with Geodesic.ALL.

Usage: python3 tools/gen_pyref.py /path/to/GeodTest-short.dat [STEP]
"""
import sys
from geographiclib.geodesic import Geodesic
g = Geodesic.WGS84
path = sys.argv[1]; step = int(sys.argv[2]) if len(sys.argv) > 2 else 10
rows = [list(map(float, l.split())) for i, l in enumerate(open(path).read().split("\n")) if l.strip() and i % step == 5]
inv = [(r[0], r[1], r[3], r[4]) for r in rows]
# edge cases: coincident, poles, equatorial, meridional, antipodal, antimeridian
inv += [(0, 0, 0, 0), (90, 0, -90, 0), (0, 0, 0, 180), (0, 0, 0, 179.5), (0, 0, 0, 90),
        (45, 10, 45, 10), (89.9999999, 30, -89.9999999, -150), (-41.32, 174.81, 40.96, -5.50),
        (30, 179.9, 30, -179.9), (0.0000001, 0, -0.0000001, 179.99999), (50, 0, 50, 180),
        (-90, 0, 90, 0), (10, 20, 10.000000001, 20.000000001), (39.9087, 116.3975, 31.2304, 121.4737)]
dirs = [(r[0], r[1], r[2], r[6]) for r in rows]
dirs += [(0, 0, 90, 20003931.4586), (90, 0, 180, 10001965.729), (40, -75, 45, 1e7),
         (-30, 150, -170, 3e7), (10, 10, 0, 0), (0, 0, 0, 40007862.917)]
def lit(v):
    r = repr(float(v))
    if r == "nan": return "@double.not_a_number"
    if "e" in r:
        m, e = r.split("e"); m += "" if "." in m else ".0"; r = m + "e" + e
    elif "." not in r: r += ".0"
    return r
out = ["// Generated by tools/gen_pyref.py with geographiclib (Python) 2.1. Do not edit.", "",
       "///|", "/// (lat1, lon1, lat2, lon2) -> s12 azi1 azi2 a12 m12 M12 M21 S12",
       "let pyref_inverse : Array[FixedArray[Double]] = ["]
for a in inv:
    o = g.Inverse(*a, outmask=Geodesic.ALL)
    vals = list(a) + [o[k] for k in ("s12", "azi1", "azi2", "a12", "m12", "M12", "M21", "S12")]
    out.append("  [" + ", ".join(map(lit, vals)) + "],")
out += ["]", "", "///|", "/// (lat1, lon1, azi1, s12) -> lat2 lon2 azi2 a12 m12 M12 M21 S12 (long_unroll)",
        "let pyref_direct : Array[FixedArray[Double]] = ["]
for a in dirs:
    o = g.Direct(*a, outmask=Geodesic.ALL | Geodesic.LONG_UNROLL)
    vals = list(a) + [o[k] for k in ("lat2", "lon2", "azi2", "a12", "m12", "M12", "M21", "S12")]
    out.append("  [" + ", ".join(map(lit, vals)) + "],")
out.append("]")
open("src/geodesic/pyref_data_test.mbt", "w").write("\n".join(out) + "\n")
print(len(inv), len(dirs))
